export const CURRENCY_RATES: Record<Currency, { rate: number; symbol: string; label: string }> = {
  EUR: { rate: 1.0, symbol: '€', label: 'EUR (€)' },
  GBP: { rate: 0.86, symbol: '£', label: 'GBP (£)' },
  CHF: { rate: 0.95, symbol: 'CHF', label: 'CHF' },
};

export function formatPrice(priceEUR: number, currency: Currency): string {
  const { rate, symbol } = CURRENCY_RATES[currency];
  const converted = (priceEUR * rate).toFixed(2);
  if (currency === 'EUR') return `${converted} €`;
  if (currency === 'GBP') return `£${converted}`;
  return `${converted} CHF`;
}

